"""Create isolated Windows candidate sources and record downloadable artifacts."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import tomllib
from pathlib import Path

from build_store_payload import safe_relative

GIT = shutil.which("git")
if not GIT:
    raise RuntimeError("Git executable is required")


def digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def git(root: Path, *arguments: str) -> bytes:
    # All call sites pass fixed Git subcommands; values remain separate argv entries.
    return subprocess.check_output([GIT, "-C", str(root), *arguments])  # noqa: S603


def source_manifest(root: Path) -> dict[str, str]:
    names = git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    deleted = set(git(root, "ls-files", "-z", "--deleted").decode("utf-8").split("\0"))
    manifest = {}
    for name in sorted(set(names.decode("utf-8").split("\0")) - {""}):
        if name in deleted:
            continue
        if name.startswith("apps/desktop/src-tauri/runtime/"):
            continue  # assembled only inside the isolated candidate build tree
        if name.startswith("apps/desktop/src-tauri/binaries/") and name.endswith(".build.json"):
            continue  # generated by the fresh engine build, never a source input
        path = safe_relative(root, name)
        if not path.is_file():
            raise ValueError(f"Source file is missing or unsupported: {name}")
        manifest[name] = digest(path)
    return manifest


def version(root: Path) -> str:
    npm = json.loads((root / "apps/desktop/package.json").read_text(encoding="utf-8"))
    npm_lock = json.loads((root / "apps/desktop/package-lock.json").read_text(encoding="utf-8"))
    tauri = json.loads(
        (root / "apps/desktop/src-tauri/tauri.conf.json").read_text(encoding="utf-8")
    )
    cargo = tomllib.loads((root / "apps/desktop/src-tauri/Cargo.toml").read_text(encoding="utf-8"))
    python = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    cargo_lock = tomllib.loads(
        (root / "apps/desktop/src-tauri/Cargo.lock").read_text(encoding="utf-8")
    )
    uv_lock = tomllib.loads((root / "uv.lock").read_text(encoding="utf-8"))
    versions = [
        npm["version"],
        npm_lock["version"],
        npm_lock["packages"][""]["version"],
        tauri["version"],
        cargo["package"]["version"],
        python["project"]["version"],
        next(p["version"] for p in cargo_lock["package"] if p["name"] == cargo["package"]["name"]),
        next(p["version"] for p in uv_lock["package"] if p["name"] == python["project"]["name"]),
    ]
    if len(set(versions)) != 1:
        raise ValueError(f"Release versions disagree across manifests/locks: {versions}")
    return versions[0]


def snapshot(root: Path, output: Path, allow_dirty: bool) -> None:
    dirty = bool(git(root, "status", "--porcelain").strip())
    if dirty and not allow_dirty:
        raise ValueError(
            "Release source is dirty; commit the reviewed candidate or use "
            "--allow-dirty for local verification"
        )
    if output.exists():
        raise ValueError("Candidate output already exists; choose a fresh directory")
    root = root.resolve()
    output = output.resolve()
    # An output inside the checkout must be ignored, otherwise copying could recurse.
    if output.is_relative_to(root):
        ignored = (
            subprocess.run(  # noqa: S603
                [GIT, "-C", str(root), "check-ignore", "-q", str(output)], check=False
            ).returncode
            == 0
        )
        if not ignored:
            raise ValueError("Candidate output within the checkout must be Git-ignored")
    candidate_version = version(root)
    manifest = source_manifest(root)
    source = output / "source"
    source.mkdir(parents=True)
    for name, expected in manifest.items():
        destination = safe_relative(source, name)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(safe_relative(root, name), destination)
        if digest(destination) != expected:
            raise ValueError(f"Source changed while copying: {name}")
    if source_manifest(root) != manifest:
        raise ValueError("Source changed during candidate preparation")
    # Enables .gitignore handling in the engineering runner's rg enumeration.
    subprocess.run([GIT, "init", "--quiet", str(source)], check=True)  # noqa: S603
    metadata = {
        "schema": 1,
        "version": candidate_version,
        "commit": git(root, "rev-parse", "HEAD").decode().strip(),
        "dirty_source": dirty,
        "source_files": manifest,
        "release_approved": False,
    }
    (output / "source-manifest.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")


def verify_snapshot(output: Path) -> dict:
    metadata = json.loads((output / "source-manifest.json").read_text(encoding="utf-8"))
    unexpected = set(source_manifest(output / "source")) - set(metadata["source_files"])
    if unexpected:
        raise ValueError(
            f"Candidate source files were added during the build: {sorted(unexpected)}"
        )
    for name, expected in metadata["source_files"].items():
        if digest(safe_relative(output / "source", name)) != expected:
            raise ValueError(f"Candidate source changed during the build: {name}")
    version(output / "source")
    return metadata


def finish(output: Path, signed: bool, engineering_passed: bool, tools_complete: bool) -> None:
    metadata = verify_snapshot(output)
    artifacts = output / "artifacts"
    installers = sorted([*artifacts.glob("*.exe"), *artifacts.glob("*.msi")])
    if not any(p.suffix == ".exe" for p in installers) or not any(
        p.suffix == ".msi" for p in installers
    ):
        raise ValueError("Both fresh NSIS and MSI installers are required")
    records = [{"file": p.name, "bytes": p.stat().st_size, "sha256": digest(p)} for p in installers]
    if engineering_passed:
        checks = json.loads((output / "engineering/checks.json").read_text(encoding="utf-8"))
        if checks.get("status") != "engineering_checks_passed":
            raise ValueError("Engineering evidence did not pass")
    report = {
        "schema": 1,
        "version": metadata["version"],
        "commit": metadata["commit"],
        "dirty_source": metadata["dirty_source"],
        "source_manifest_sha256": digest(output / "source-manifest.json"),
        "signing": "authenticode-verified" if signed else "unsigned-local-candidate",
        "release_approved": False,
        "engineering_checks_passed": engineering_passed,
        "bundled_tools_complete": tools_complete,
        "remaining_gates": "Installed-app, real-model, Desktop and distribution acceptance",
        "artifacts": records,
    }
    for name in ("runtime-input-manifest.json", "runtime-signatures.json"):
        path = artifacts / name
        if path.is_file():
            report[name.replace(".json", "").replace("-", "_") + "_sha256"] = digest(path)
    (artifacts / "candidate.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (artifacts / "SHA256SUMS.txt").write_text(
        "".join(f"{entry['sha256']}  {entry['file']}\n" for entry in records), encoding="utf-8"
    )
    shutil.copyfile(output / "source-manifest.json", artifacts / "source-manifest.json")


def qualify_artifacts(artifacts: Path, qualification: Path, commit: str) -> str:
    """Bind an explicit reviewed qualification record to exact downloadable bytes."""
    candidate_path = artifacts / "candidate.json"
    candidate = json.loads(candidate_path.read_text(encoding="utf-8"))
    review = json.loads((qualification / "qualification.json").read_text(encoding="utf-8"))
    if (
        candidate.get("commit") != commit
        or candidate.get("dirty_source") is not False
        or candidate.get("signing") != "authenticode-verified"
        or candidate.get("engineering_checks_passed") is not True
        or candidate.get("bundled_tools_complete") is not True
    ):
        raise ValueError("Candidate is incomplete, unsigned or not bound to the reviewed commit")
    if (
        review.get("schema") != 1
        or review.get("approved_for_distribution") is not True
        or review.get("source_commit") != commit
        or review.get("candidate_manifest_sha256") != digest(candidate_path)
        or not review.get("reviewed_by")
        or not review.get("reviewed_at")
    ):
        raise ValueError("Explicit artifact-bound distribution qualification is missing")
    gates = {
        "clean_windows_install",
        "upgrade_uninstall",
        "real_model_corpus",
        "powerbi_desktop",
        "offline_operation",
        "licenses_reviewed",
        "security_review",
    }
    for gate in gates:
        result = review.get("gates", {}).get(gate, {})
        if result.get("passed") is not True or not result.get("evidence"):
            raise ValueError(f"Required qualification gate is missing: {gate}")
    if digest(artifacts / "source-manifest.json") != candidate["source_manifest_sha256"]:
        raise ValueError("Candidate source manifest differs")
    expected = {entry["file"]: entry["sha256"] for entry in candidate["artifacts"]}
    actual_names = {path.name for path in artifacts.iterdir() if path.suffix in {".exe", ".msi"}}
    if actual_names != set(expected) or not {".exe", ".msi"}.issubset(
        {Path(name).suffix for name in expected}
    ):
        raise ValueError("Installer inventory differs from the candidate")
    for name, expected_hash in expected.items():
        if digest(safe_relative(artifacts, name)) != expected_hash:
            raise ValueError(f"Qualified installer bytes changed: {name}")
    if digest(qualification / "release-notes.md") != review.get("release_notes_sha256"):
        raise ValueError("Reviewed release notes differ")
    return candidate["version"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["snapshot", "verify", "finish", "qualify"])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--allow-dirty", action="store_true")
    parser.add_argument("--signed", action="store_true")
    parser.add_argument("--engineering-passed", action="store_true")
    parser.add_argument("--tools-complete", action="store_true")
    parser.add_argument("--qualification", type=Path)
    parser.add_argument("--commit")
    args = parser.parse_args()
    if args.mode == "snapshot":
        snapshot(args.root, args.output, args.allow_dirty)
    elif args.mode == "verify":
        verify_snapshot(args.output)
    elif args.mode == "finish":
        finish(args.output, args.signed, args.engineering_passed, args.tools_complete)
    else:
        if not args.qualification or not args.commit:
            parser.error("qualify requires --qualification and --commit")
        print(qualify_artifacts(args.output, args.qualification, args.commit))


if __name__ == "__main__":
    main()
